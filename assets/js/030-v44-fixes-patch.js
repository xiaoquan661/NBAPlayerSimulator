/* ---------- 生涯状态探测 ---------- */
/* 是否换过队（任意两个相邻赛季球队不同） */
function v44HasLeft(){
  try{
    const hist=(career&&career.history)||[];
    for(let i=1;i<hist.length;i++){
      if(hist[i]&&hist[i-1]&&hist[i].team&&hist[i-1].team&&hist[i].team!==hist[i-1].team)return true;
    }
    /* 当前赛季也要和历史最后一季比 */
    if(hist.length&&hist[hist.length-1]&&hist[hist.length-1].team&&career.team&&hist[hist.length-1].team!==career.team)return true;
  }catch(e){}
  return false;
}
/* 是否离开过「选秀球队」（用于「回到旧地」这类章节） */
function v44LeftDraftTeam(){
  try{
    const hist=(career&&career.history)||[];
    if(v44HasLeft())return true;
    /* 再比对：当前球队 vs 生涯首季球队 */
    const firstTeam=(hist.length&&hist[0]&&hist[0].team)?hist[0].team:null;
    const cur=(career&&career.team)||null;
    if(firstTeam&&cur&&firstTeam!==cur)return true;
  }catch(e){}
  return false;
}
/* 是否还在选秀球队 */
function v44StillDraftTeam(){
  try{
    const hist=(career&&career.history)||[];
    let firstTeam=null;
    if(hist.length&&hist[0]&&hist[0].team)firstTeam=hist[0].team;
    const cur=(career&&career.team)||null;
    if(!firstTeam)return true;              /* 第 1 季：还没记录历史 */
    return firstTeam===cur;
  }catch(e){}
  return true;
}
