function v48IdxOf(pid,ev){
  try{
    const arr=(typeof campaigns!=='undefined'&&campaigns&&campaigns[pid])||[];
    for(let i=0;i<arr.length;i++)if(arr[i]===ev)return i;
  }catch(e){}
  return -1;
}
function v48WrapEvent(ev){
  try{
    if(!ev)return ev;
    if(ev._v48)return ev;                       /* 已解析过 */
    const pid=(career&&career.playerId)||'';
    const reg=window.__v48Reg&&window.__v48Reg[pid];
    if(!reg)return ev;
    const i=v48IdxOf(pid,ev);
    const entry=reg[i];
    if(!entry||!entry.variants)return ev;
    const snap=window.v48Snap();
    return window.v48Resolve(Object.assign({},ev,entry),snap);
  }catch(e){return ev}
}
